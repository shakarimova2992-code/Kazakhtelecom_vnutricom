function t(key, lang, vars) {
  const dict = I18N[lang] || I18N.ru;
  let str = dict[key];
  if (str === undefined) str = I18N.ru[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.replace(`{${k}}`, vars[k]);
    });
  }
  return str;
}
